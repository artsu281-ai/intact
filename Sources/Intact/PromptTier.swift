import Foundation

/// Насколько подробным должен быть системный промпт.
///
/// Промпты причёсывания и быстрого ответа писались и выверялись на локальной
/// модели в 2–4 миллиарда параметров, и заметная часть их объёма — костыли под
/// неё: примеры «вход → выход», закрытый список слов-паразитов, троекратный
/// повтор одного и того же запрета. Сильной модели они не помогают, а мешают:
/// «Пример 3» в причёсывании демонстрировал ровно то сокращение, которое
/// запрещено абзацем выше (9 слов → 5), а примеры «плохо/хорошо» в быстром
/// ответе задавали шаблон «отвечай одним словом на всё».
///
/// Обратное тоже верно: без примеров локальная модель не удерживала формат.
/// Поэтому уровень выбирается по тому, кто реально будет выполнять запрос,
/// а подробный вариант остаётся дословно таким, каким он был выверен.
enum PromptTier {
    /// Сильная модель: задача, границы и ни одного примера.
    case compact
    /// Локальная модель: то же самое, но с примерами, перечнями и повторами.
    case detailed

    /// Уровень обязан считаться тем же предикатом, что и маршрут.
    ///
    /// У пайплайнов есть собственный запасной выход в Gemini.app
    /// (`requestPipelineAI`), поэтому «модель для роли не выбрана» означает не
    /// «промпт никуда не уйдёт», а «уйдёт в Gemini». На чистой установке это
    /// не угол, а поведение по умолчанию: `aiLocalModelPath` пуст, то есть
    /// `AIModelCatalog.current == .disabled`, и правый ⌥ идёт через Gemini.app.
    static func resolved(for role: AIRole) -> PromptTier {
        guard AIRouter.shared.isReady(for: role) else { return .compact }
        return AIModelCatalog.resolved(for: role).promptTier
    }
}

extension AIModelChoice {
    var promptTier: PromptTier {
        switch self {
        case .gemini:   return .compact
        case .local:    return .detailed
        case .disabled: return .compact
        }
    }
}

/// Системная инструкция и пользовательская часть одного запроса.
///
/// Они выбираются вместе, а не по отдельности, потому что на пути к Gemini
/// ролей не существует: `GeminiAIProvider.formatPrompt` склеивает всё в одно
/// сообщение «Инструкция: …\n\n<текст>», и границу между инструкцией и
/// материалом приходится ставить самим — меткой в пользовательской части.
/// У локального пути роли настоящие, и метка там не нужна.
struct AIPrompt {
    let system: String
    let user: String
}
